<h1>jpx ?</h1>
<p>
    jpx is a javascript image processing library.
<h2>Predefined filter</h2>
<div>
    Numerous filters are already embedded inside jpx core library.
    <ul>
        <li>desaturation</li>
        <li>negative</li>
        <li>sepia tone</li>
        <li>color adjustment</li>
        <li>brightness / contrast</li>
        <li>saturation control</li>
        <li>...</li>
    </ul>
</div>

<h2>Easy</h2>
<div>
    The provided <a href="jpx/docs/api" target="_blank">documentation</a>
    and the <a href="?p=examples">examples</a> make this jpx a library easy to use.
</div>

<h2>Extensible</h2>
<div>
    jpx was designed to provide a highly simple way to design
    custom filters that can be directly used on jpx images.<br/>
    See the <a href="?p=getstarted#create-plugin">get started</a> page for more details.
</div>
